INSERT dbo.Lending_Contract (Contract_No, Stock_ID, Borrowed_Qty, Collateral_Val)
SELECT 'CT' + CONVERT(char(8), DATEADD(DAY, (n.n - 1) / 50, '20260401'), 112)       -- CT + 開約日(0401~0420，前 19 天每天 50 筆，0420 為 43 筆)
          + RIGHT('00' + CAST((n.n - 1) % 50 + 1 AS varchar(2)), 2)                     -- + 2 位流水號，與題目範例 CT2026042401 同格式
      ,s.Stock_ID
      ,q.Qty
      ,CAST(q.Qty * 1000 * s.Px * r.Ratio AS decimal(18,2))      -- 借出市值 × 擔保比例
FROM n
    JOIN s ON s.i = (n.n * 11 + n.n / 7) % 50
    CROSS APPLY (VALUES (1 + (n.n * 53 + n.n / 3) % 60)) q(Qty)
    -- 由 n 決定狀態區間(每 100 筆：6 筆處置、14 筆預警、80 筆正常)與區間內的位置，結果固定、可重現
    CROSS APPLY (VALUES (n.n * 37 % 100, (n.n * 7919 % 1000) / 1000.0)) b(Bucket, Frac)
    CROSS APPLY (VALUES (CAST(CASE WHEN b.Bucket < 6  THEN 1.05  + b.Frac * 0.14     -- 處置：105%~119%
                                   WHEN b.Bucket < 20 THEN 1.205 + b.Frac * 0.18     -- 預警：120.5%~138.5%
                                   ELSE                    1.405 + b.Frac * 0.495    -- 正常：140.5%~190%
                              END AS decimal(9,4)))) r(Ratio);

